CREATE TABLE study_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_profile_id UUID NOT NULL REFERENCES application_profiles(id) ON DELETE CASCADE,
    source_session_id VARCHAR(128),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    target_completion_percent NUMERIC(5,2) NOT NULL DEFAULT 80.00
        CHECK (target_completion_percent BETWEEN 0 AND 100),
    target_date DATE,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE sessions ADD CONSTRAINT uq_sessions_profile_and_id UNIQUE (application_profile_id, id);
ALTER TABLE study_plans ADD CONSTRAINT fk_study_plan_source
    FOREIGN KEY (application_profile_id, source_session_id)
    REFERENCES sessions(application_profile_id, id) ON DELETE SET NULL (source_session_id);
CREATE UNIQUE INDEX uq_study_plans_active_profile ON study_plans(application_profile_id) WHERE status = 'ACTIVE';
CREATE INDEX idx_study_plans_profile_source ON study_plans(application_profile_id, source_session_id);

CREATE TABLE study_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES study_plans(id) ON DELETE CASCADE,
    skill_id TEXT,
    title VARCHAR(255) NOT NULL,
    notes TEXT,
    status VARCHAR(16) NOT NULL DEFAULT 'TODO' CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    sort_order INT NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((status = 'DONE') = (completed_at IS NOT NULL))
);
CREATE INDEX idx_study_tasks_plan_order ON study_tasks(plan_id, sort_order, id);

CREATE TABLE study_task_resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES study_tasks(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    url VARCHAR(2048),
    file_name VARCHAR(255),
    file_data BYTEA,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (url IS NOT NULL AND file_name IS NULL AND file_data IS NULL)
        OR (url IS NULL AND file_name IS NOT NULL AND file_data IS NOT NULL
            AND octet_length(file_data) BETWEEN 1 AND 10485760)
    )
);
CREATE INDEX idx_study_task_resources_task ON study_task_resources(task_id, id);

CREATE TABLE study_task_checklist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES study_tasks(id) ON DELETE CASCADE,
    content VARCHAR(500) NOT NULL,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INT NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (is_completed = (completed_at IS NOT NULL))
);
CREATE INDEX idx_study_task_checklist_task_order ON study_task_checklist_items(task_id, sort_order, id);
