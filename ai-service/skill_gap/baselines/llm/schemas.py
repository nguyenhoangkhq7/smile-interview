from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from skill_gap.domain.enums import SemanticAlignment


class LLMSkillAssessment(BaseModel):
    """
    Schema for a single skill assessment in the LLM Chain-of-Thought output.
    Crucial design: 'reasoning' precedes the numerical conclusions so that
    the language model generates explicit analytical thinking before generating numbers.
    """
    jd_skill_id: str = Field(
        description="The exact identifier of the JD requirement skill being evaluated."
    )
    reasoning: str = Field(
        description=(
            "Step-by-step analytical reasoning: (a) verbatim evidence in CV, "
            "(b) duration and autonomy level, (c) candidate proficiency (P_CV), "
            "(d) required proficiency (P_JD), (e) gap magnitude and interview priority."
        )
    )
    evidence_quote: Optional[str] = Field(
        default=None,
        description="Verbatim snippet copied directly from the CV text proving this skill, or null if no evidence exists."
    )
    semantic_alignment: SemanticAlignment = Field(
        description="Categorization: MATCH (direct skill match), PARTIAL (transferable equivalent skill), MISSING (unsupported)."
    )
    candidate_proficiency: float = Field(
        ge=1.0,
        le=5.0,
        description="Candidate mastery level (P_CV) on a 1.0 to 5.0 scale according to the rubric."
    )
    required_proficiency: float = Field(
        ge=1.0,
        le=5.0,
        description="Required mastery level (P_JD) on a 1.0 to 5.0 scale demanded by the JD."
    )
    gap_magnitude: float = Field(
        ge=0.0,
        le=1.0,
        description="Normalized gap magnitude representing the shortfall in candidate proficiency [0.0 = no gap, 1.0 = missing]."
    )
    priority: float = Field(
        ge=0.0,
        le=1.0,
        description="Interview urgency rating [0.0 = low priority, 1.0 = critical to probe during interview]."
    )


class LLMZeroShotResponse(BaseModel):
    """
    Full JSON response object generated by the zero-shot LLM baseline.
    Must contain assessment for all required skills.
    """
    skills: List[LLMSkillAssessment] = Field(
        description="List of structured assessments for each demanded JD skill."
    )


class RunAuditRecord(BaseModel):
    """
    Audit log record stored to disk for post-hoc error analysis.
    Preserves verbatim reasoning and prompt hashes without contaminating numerical metrics.
    """
    run_id: str
    prompt_hash: str
    baseline_name: str
    model_name: str
    prompt_text: str
    raw_response_text: str
    assessments: List[Dict[str, Any]]
    created_at: str
